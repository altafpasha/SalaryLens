FIXTURES_DIR = Path("fixtures/synthetic_statements")


def test_indra_ocr_engine_initialization():
    """Verifies Indra OCR converter lazy loading and singleton instance."""
    conv = IndraOCREngine.get_converter()
    assert conv is not None


def test_ocr_table_parser_safe_decimal_and_overflow_guard():
    """Verifies safe decimal conversion and rejection of UTR/account number overflows."""
    assert OCRTableParser.safe_decimal("5,250.00") == Decimal("5250.00")
    assert OCRTableParser.safe_decimal("₹ 32,865.50") == Decimal("32865.50")
    assert OCRTableParser.safe_decimal("-") is None
    assert OCRTableParser.safe_decimal("N/A") is None
    # Boundary: numbers >= 10^10 must be rejected
    assert OCRTableParser.safe_decimal("10016402891") is None
    assert OCRTableParser.safe_decimal("99999999999") is None


def test_ocr_table_parser_date_parsing():
    """Verifies date parser converts varied bank date formats to ISO YYYY-MM-DD."""
    assert OCRTableParser.parse_date("31-Mar-2026") == "2026-03-31"
    assert OCRTableParser.parse_date("30/04/2026") == "2026-04-30"
    assert OCRTableParser.parse_date("2026-05-30") == "2026-05-30"
    assert OCRTableParser.parse_date("15/03/26") == "2026-03-15"
    assert OCRTableParser.parse_date("invalid") is None


def test_ocr_table_parser_markdown_table_extraction():
    """Verifies extraction of structured transactions from markdown pipe tables."""
    md_table = """
| Date | Description | Debit | Credit | Balance |
|---|---|---|---|---|
| 2026-03-31 | ACH CREDIT ACME TECH CORP SALARY | - | 5,250.00 | 12,500.00 |
| 2026-04-30 | ACH CREDIT ACME TECH CORP SALARY | - | 5,250.00 | 17,750.00 |
| 2026-05-30 | ACH CREDIT ACME TECH CORP SALARY | - | 5,250.00 | 23,000.00 |
"""
    txs = OCRTableParser.extract_transactions_from_markdown(md_table, page_number=1)
    assert len(txs) == 3
    assert txs[0]["transaction_date"] == "2026-03-31"
    assert txs[0]["credit_amount"] == Decimal("5250.00")
    assert txs[0]["page_number"] == 1
    assert "ACME TECH" in txs[0]["description"]


