def test_hybrid_pipeline_fast_path_native_pdf():
    """Verifies clean digital statement takes fast-path native extraction."""
    pipeline = HybridDocumentPipeline()
    norm = pipeline.extract_document(str(FIXTURES_DIR / "01_clear_monthly_salary.pdf"))
    assert norm.total_pages == 1
    assert norm.is_scanned is False
    assert norm.native_pages_count >= 1
    assert len(norm.table_transactions) >= 3
    # Check deduplication
    dates = [t["transaction_date"] for t in norm.table_transactions]
    assert len(dates) == len(set(dates))  # No duplicated transaction rows


def test_hybrid_pipeline_scanned_detection():
    """Verifies scanned statement is correctly flagged and routes to Indra OCR."""
    pipeline = HybridDocumentPipeline()
    norm = pipeline.extract_document(str(FIXTURES_DIR / "09_unreadable_scanned.pdf"))
    assert norm.is_scanned is True
    assert norm.engine_used == "hybrid_indra"


def test_document_extractor_normalized_document_method():
    """Verifies DocumentExtractor.extract_normalized_document returns NormalizedDocument IR."""
    norm = DocumentExtractor.extract_normalized_document(str(FIXTURES_DIR / "01_clear_monthly_salary.pdf"))
    assert isinstance(norm, NormalizedDocument)
    assert len(norm.pages) > 0
    assert isinstance(norm.pages[0], NormalizedPage)
